package guided1.asosiasi; 
 
public class Mahasiswa { 
    private String nim; 
    private String nama; 
    private int nilai; 
 
    public void setNim(String nim) { 
        this.nim = nim; 
    } 
 
    public String getNim() { 
        return this.nim; 
    } 
 
    public void setNama(String nama) { 
        this.nama = nama; 
    } 
 
    public String getNama() { 
        return this.nama; 
    } 
 
    public void setNilai(int nilai) { 
        this.nilai = nilai; 
    } 
 
    public int getNilai() { 
        return this.nilai; 
    } 
} 